export type StatementEntry = {
  date: string;
  reference_number: string;
  transaction_type: string;
  entry_type: string;
  description: string;
  amount: string;
  balance_after: string;
};

export type StatementPdfInput = {
  customerName: string;
  customerEmail: string;
  customerAddress: string;
  accountNumber: string;
  accountType: string;
  accountStatus: string;
  currency: string;
  startDate: string;
  endDate: string;
  openingBalance: string;
  totalCredits: string;
  totalDebits: string;
  closingBalance: string;
  entries: StatementEntry[];
};

function escapePdfText(input: string): string {
  return input
    .replaceAll("\\", "\\\\")
    .replaceAll("(", "\\(")
    .replaceAll(")", "\\)")
    .replace(/[^\x20-\x7E]/g, "?");
}

function drawText(x: number, y: number, font: "F1" | "F2", size: number, text: string): string {
  return `BT /${font} ${size} Tf 1 0 0 1 ${x} ${y} Tm (${escapePdfText(text)}) Tj ET\n`;
}

export function buildStatementPdf(data: StatementPdfInput): Buffer {
  const linesPerPage = 32;
  const entryChunks: StatementEntry[][] = [];
  if (data.entries.length === 0) {
    entryChunks.push([]);
  } else {
    for (let i = 0; i < data.entries.length; i += linesPerPage) {
      entryChunks.push(data.entries.slice(i, i + linesPerPage));
    }
  }

  const objects: string[] = [];
  const addObj = (body: string): number => {
    objects.push(body);
    return objects.length;
  };

  const fontRegularId = addObj("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const fontBoldId = addObj("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>");

  const pageIds: number[] = [];
  const pagesPlaceholderId = addObj("");

  entryChunks.forEach((chunk, pageIndex) => {
    let stream = "";
    // Navy header banner
    stream += "0.039 0.145 0.251 rg 36 720 540 50 re f\n";
    stream += "1 1 1 rg\n";
    stream += drawText(50, 748, "F2", 16, "Online Banking Demo - Account Statement");
    stream += drawText(50, 731, "F1", 9, `Generated: ${new Date().toISOString().slice(0, 19).replace("T", " ")} UTC   |   Page ${pageIndex + 1} of ${entryChunks.length}`);

    // Light blue account summary box
    stream += "0.922 0.957 1.0 rg 36 628 540 80 re f\n";
    stream += "0.059 0.090 0.165 rg\n";
    stream += drawText(48, 690, "F2", 10, `Account Holder: ${data.customerName}`);
    stream += drawText(48, 675, "F1", 9, `Email: ${data.customerEmail}`);
    stream += drawText(48, 660, "F1", 9, `Address: ${data.customerAddress || "Not provided"}`);

    stream += drawText(330, 690, "F2", 10, `Account: #${data.accountNumber} (${data.accountType})`);
    stream += drawText(330, 675, "F1", 9, `Status: ${data.accountStatus}   |   Currency: ${data.currency}`);
    stream += drawText(330, 660, "F1", 9, `Period: ${data.startDate} to ${data.endDate}`);
    stream += drawText(
      48,
      640,
      "F2",
      9,
      `Opening: ${data.currency} ${data.openingBalance}   |   Credits: +${data.totalCredits}   |   Debits: -${data.totalDebits}   |   Closing: ${data.currency} ${data.closingBalance}`
    );

    // Table header
    stream += "0.039 0.145 0.251 rg 36 594 540 22 re f\n";
    stream += "1 1 1 rg\n";
    stream += drawText(44, 601, "F2", 8.5, "DATE (UTC)");
    stream += drawText(128, 601, "F2", 8.5, "REFERENCE");
    stream += drawText(265, 601, "F2", 8.5, "TYPE");
    stream += drawText(330, 601, "F2", 8.5, "DESCRIPTION");
    stream += drawText(462, 601, "F2", 8.5, "AMOUNT");
    stream += drawText(522, 601, "F2", 8.5, "BALANCE");

    stream += "0.059 0.090 0.165 rg\n";
    if (chunk.length === 0) {
      stream += drawText(44, 574, "F1", 9, "No ledger entries recorded during this statement period.");
    } else {
      let y = 576;
      for (const entry of chunk) {
        const signedAmt = `${entry.entry_type === "CREDIT" ? "+" : "-"}${entry.amount}`;
        stream += drawText(44, y, "F1", 8, entry.date.slice(0, 16).replace("T", " "));
        stream += drawText(128, y, "F1", 8, entry.reference_number.slice(0, 24));
        stream += drawText(265, y, "F1", 8, entry.transaction_type);
        stream += drawText(330, y, "F1", 8, (entry.description || "-").slice(0, 22));
        stream += drawText(462, y, "F1", 8, signedAmt);
        stream += drawText(522, y, "F1", 8, entry.balance_after);
        y -= 16;
      }
    }

    stream += "0.392 0.455 0.545 rg\n";
    stream += drawText(
      36,
      36,
      "F1",
      8,
      "NOTICE: Generated by Online Banking Demo (local demonstration only; does not represent real funds)."
    );

    const streamBytes = Buffer.byteLength(stream, "utf8");
    const contentId = addObj(`<< /Length ${streamBytes} >>\nstream\n${stream}endstream`);
    const pageId = addObj(
      `<< /Type /Page /Parent ${pagesPlaceholderId} 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${fontRegularId} 0 R /F2 ${fontBoldId} 0 R >> >> /Contents ${contentId} 0 R >>`
    );
    pageIds.push(pageId);
  });

  objects[pagesPlaceholderId - 1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pageIds.length} >>`;
  const catalogId = addObj(`<< /Type /Catalog /Pages ${pagesPlaceholderId} 0 R >>`);

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [0];
  for (let i = 0; i < objects.length; i += 1) {
    offsets.push(Buffer.byteLength(pdf, "utf8"));
    pdf += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`;
  }

  const xrefStart = Buffer.byteLength(pdf, "utf8");
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (let i = 1; i <= objects.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(pdf, "utf8");
}
